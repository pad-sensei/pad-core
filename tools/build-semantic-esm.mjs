import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const TOOL_FILE = fileURLToPath(import.meta.url);
const DEFAULT_ROOT = resolve(dirname(TOOL_FILE), '..');
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function assertManifest(manifest) {
  if (!manifest || manifest.namespace !== 'PadSenseiTheory') {
    throw new Error('semantic manifest namespace must be PadSenseiTheory');
  }
  if (!Array.isArray(manifest.classicSourceLoadOrder) || !manifest.classicSourceLoadOrder.length) {
    throw new Error('semantic manifest must declare classicSourceLoadOrder');
  }
  if (!Array.isArray(manifest.symbols) || !manifest.symbols.length) {
    throw new Error('semantic manifest must declare public symbols');
  }

  const sourceOrder = manifest.classicSourceLoadOrder;
  if (new Set(sourceOrder).size !== sourceOrder.length) {
    throw new Error('semantic manifest source order contains duplicates');
  }
  if (sourceOrder[sourceOrder.length - 1] !== 'semantic-api.js') {
    throw new Error('semantic-api.js must be the final classic source');
  }

  const publicNames = manifest.symbols.map((symbol) => symbol.public);
  if (new Set(publicNames).size !== publicNames.length) {
    throw new Error('semantic manifest public symbols contain duplicates');
  }
  for (const name of publicNames) {
    if (!IDENTIFIER.test(name)) throw new Error(`semantic public name is not an ESM identifier: ${name}`);
  }

  const declaredSources = new Set(sourceOrder);
  for (const symbol of manifest.symbols) {
    if (!declaredSources.has(symbol.sourceFile)) {
      throw new Error(`semantic source file missing from classicSourceLoadOrder: ${symbol.sourceFile}`);
    }
  }
}

export async function buildSemanticEsm({ rootDir = DEFAULT_ROOT } = {}) {
  const manifestPath = resolve(rootDir, 'semantic-api.manifest.json');
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  assertManifest(manifest);

  const sourceChunks = [];
  for (const sourceFile of manifest.classicSourceLoadOrder) {
    const source = await readFile(resolve(rootDir, sourceFile), 'utf8');
    sourceChunks.push(`// ---- ${sourceFile} ----\n${source.trimEnd()}\n`);
  }

  const namedExports = manifest.symbols
    .map((symbol) => `export const ${symbol.public} = PadSenseiTheory.${symbol.public};`)
    .join('\n');

  const code = [
    '// @generated by tools/build-semantic-esm.mjs — do not edit by hand.',
    '// Source of truth: semantic-api.manifest.json + declared classic pad-core sources.',
    'const __PadSenseiTheoryModule = (() => {',
    '  // semantic-api.js writes to globalThis for classic-script compatibility.',
    '  // Shadow it here so importing the ESM bundle never mutates the real global object.',
    '  const globalThis = Object.create(null);',
    sourceChunks.join('\n'),
    '  return PadSenseiTheory;',
    '})();',
    '',
    'export const PadSenseiTheory = __PadSenseiTheoryModule;',
    namedExports,
    '',
  ].join('\n');

  return { code, manifest };
}

export async function writeSemanticEsm(outputPath, options = {}) {
  const { code, manifest } = await buildSemanticEsm(options);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, code, 'utf8');
  return { outputPath, manifest };
}

if (process.argv[1] && resolve(process.argv[1]) === TOOL_FILE) {
  const outputPath = resolve(process.argv[2] || resolve(DEFAULT_ROOT, 'dist/pad-sensei-theory.mjs'));
  await writeSemanticEsm(outputPath);
  process.stdout.write(`${outputPath}\n`);
}
